// USBKeyCode returns the physical code for a keyboard-page HID usage.
func USBKeyCode(usage uint16) string {
	for _, p := range keyPositions {
		if p.usb == usage {
			return p.name
		}
	}
	return ""
}

// AppKitKeyCode returns the physical code for an NSEvent key code.
func AppKitKeyCode(code uint16) string {
	for _, p := range keyPositions {
		if p.mac != 0xffff && p.mac == code {
			return p.name
		}
	}
	return ""
}

// XKBKeyCode returns the physical code for an XKB hardware key code.
func XKBKeyCode(code uint16) string {
	if code != 0 {
		for _, p := range keyPositions {
			if p.xkb == code {
				return p.name
			}
		}
	}
	return ""
}

// WinKeyCode returns the physical code for a set-1 scan code with its
// extended 0xe0 prefix, when applicable.
func WinKeyCode(scan uint16) string {
	if scan != 0 {
		for _, p := range keyPositions {
			if p.windows == scan {
				return p.name
			}
		}
	}
	return ""
}

// USKeyName is the unmodified logical key name for a physical code on
// the US layout, for nsgotest's headless keyboard.
func USKeyName(code string) string {
	switch {
	case len(code) == 4 && strings.HasPrefix(code, "Key"):
		return strings.ToLower(code[3:])
	case len(code) == 6 && strings.HasPrefix(code, "Digit"):
		return code[5:]
	case len(code) == 7 && strings.HasPrefix(code, "Numpad"):
		return code[6:]
	case strings.HasPrefix(code, "Arrow"):
		return strings.ToLower(code[5:])
	}
	switch code {
	case "ControlLeft", "ControlRight":
		return "ctrl"
	case "ShiftLeft", "ShiftRight":
		return "shift"
	case "AltLeft", "AltRight":
		return "alt"
	case "MetaLeft", "MetaRight":
		return "meta"
	case "NumpadEnter":
		return "enter"
	}
	if key, ok := usKeyPunctuation[code]; ok {
		return key
	}
	for _, p := range keyPositions {
		if p.name == code {
			return strings.ToLower(code)
		}
	}
	return ""
}

var usKeyPunctuation = map[string]string{
	"Backquote": "`", "Minus": "-", "Equal": "=", "BracketLeft": "[", "BracketRight": "]",
	"Backslash": "\\", "Semicolon": ";", "Quote": "'", "Comma": ",", "Period": ".", "Slash": "/",
	"NumpadAdd": "+", "NumpadSubtract": "-", "NumpadMultiply": "*", "NumpadDivide": "/", "NumpadDecimal": ".",
}
